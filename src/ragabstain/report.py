"""Markdown results page built from the JSON outputs in ``reports/``."""

from __future__ import annotations

import json
from pathlib import Path


def _row(name: str, s: dict) -> str:
    return (
        f"| {name} | {s['f1']:.3f} | {s['em']:.3f} | {s['has_ans_f1']:.3f} | "
        f"{s['no_ans_acc']:.3f} | {s['hallucination_rate']:.3f} | {s['answer_rate']:.3f} |"
    )


HEADER = [
    "| Policy | F1 | EM | Answerable F1 | Unanswerable accuracy | Hallucination rate "
    "| Answer rate |",
    "|---|---|---|---|---|---|---|",
]


def write_report(reports: Path) -> Path:
    parts = ["# Results\n", "Generated by `ragabstain report`.\n"]
    for name in ("retrieval.json", "retrieval_bm25.json"):
        path = reports / name
        if path.exists():
            res = json.loads(path.read_text())
            parts += [
                f"## Passage retrieval ({name})\n",
                "| Retriever | R@1 | R@3 | R@5 | R@10 |",
                "|---|---|---|---|---|",
            ]
            for k, v in res.items():
                parts.append(
                    f"| {k} | {v['recall@1']:.3f} | {v['recall@3']:.3f} | "
                    f"{v['recall@5']:.3f} | {v['recall@10']:.3f} |"
                )
            parts.append("")
    for path in sorted(reports.glob("abstention_*.json")):
        res = json.loads(path.read_text())
        parts += [
            f"## Abstention policies, retriever = {res['retriever']} (k={res['k']}), "
            f"{res['n_test']} test questions\n",
            *HEADER,
        ]
        parts += [_row(n, s) for n, s in res["policies"].items()]
        sel = res["selective"]
        parts += [
            "",
            "| Confidence signal | AURC (lower is better) | Acc @25% cov | Acc @50% cov "
            "| Acc @80% cov |",
            "|---|---|---|---|---|",
        ]
        for n, s in sel.items():
            parts.append(
                f"| {n} | {s['aurc']:.3f} | {s['acc@25%cov']:.3f} | "
                f"{s['acc@50%cov']:.3f} | {s['acc@80%cov']:.3f} |"
            )
        parts.append(
            f"\nLearned gate ECE: {res['calibration_ece']['learned gate']:.3f}. "
            f"Latency per question: retrieval {res['latency_ms']['retrieval']:.1f} ms, "
            f"reader over k passages {res['latency_ms']['reader_k_passages']:.1f} ms "
            "(RTX 4060 laptop GPU).\n"
        )
    for path in sorted(reports.glob("llm_*.json")):
        res = json.loads(path.read_text())
        parts += [
            f"## Generative reader {res['model']} vs extractive reader + gate "
            f"({res['n']} balanced test questions)\n",
            *HEADER,
            _row(f"LLM alone ({res['model'].split('/')[-1]})", res["llm"]),
        ]
        if "reader+gate_same_questions" in res:
            parts.append(
                _row("extractive reader + learned gate", res["reader+gate_same_questions"])
            )
            parts.append(_row("learned gate -> LLM", res["gate+llm"]))
        parts.append(
            f"\nLLM median latency: {res['median_latency_s']:.2f} s per question "
            "(RTX 4060 laptop GPU, 8 GB).\n"
        )
    out = reports / "results.md"
    out.write_text("\n".join(parts), encoding="utf-8")
    return out
